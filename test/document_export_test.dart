import 'dart:convert';

import 'package:archive/archive.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:ziongzou/features/boq/boq_document.dart';
import 'package:ziongzou/features/proposal/proposal_document.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('proposal exports a branded Word document with company footer',
      () async {
    final logo = (await rootBundle.load('assets/ahead_africa_logo.png'))
        .buffer
        .asUint8List();
    final bytes = await createProposalDocument(
      values: const {
        'Proposal title': 'Network upgrade',
        'Client': 'Example Client',
        'Client contact': 'contact@example.test',
        'Site / location': 'Dar es Salaam',
        'Reference': 'PROP-001',
        'Date': '2026-11-14',
        'Technician name': 'Technician',
        'Background / Problem': 'Intermittent connection',
        'Proposed solution / Scope of work': 'Replace and configure switches',
        'Deliverables': 'Configured network',
        'Implementation plan / Timeline': 'Two days',
        'Investment / Cost': 'TZS 100,000',
        'Payment terms': 'Upon completion',
        'Proposal validity': '30 days',
        'Assumptions / Exclusions': 'Civil works excluded',
      },
      logoBytes: logo,
    );
    final archive = ZipDecoder().decodeBytes(bytes);
    final document =
        utf8.decode(archive.findFile('word/document.xml')!.content);
    final footer = archive.files
        .where((file) => file.name.startsWith('word/footer'))
        .map((file) => utf8.decode(file.content))
        .join();
    final relationships = archive.files
        .where((file) => file.name.endsWith('.rels'))
        .map((file) => utf8.decode(file.content))
        .join();
    final images =
        archive.files.where((file) => file.name.startsWith('word/media/'));

    expect(document, contains('Network upgrade'));
    expect(document, contains('Intermittent connection'));
    expect(footer, contains('Garden Avenue Tower'));
    expect(footer, contains('+255 690 255 556'));
    expect(footer, contains('https://aheadafrica.co.tz'));
    expect(relationships, contains('https://aheadafrica.co.tz'));
    expect(images, isNotEmpty);
    expect(images.first.content, orderedEquals(logo));
    expect('$document$footer', isNot(contains('Generated by ZIONGZOU')));
  });

  test('proposal omits sections and metadata that were left blank', () async {
    final logo = (await rootBundle.load('assets/ahead_africa_logo.png'))
        .buffer
        .asUint8List();
    final bytes = await createProposalDocument(
      values: const {
        'Proposal title': 'Short proposal',
        'Client': 'Example Client',
        'Technician name': 'Technician',
        'Proposed solution / Scope of work': 'Configure the new network',
        'Client contact': '',
        'Site / location': '',
        'Reference': '',
        'Date': '',
        'Background / Problem': '',
        'Deliverables': '',
        'Implementation plan / Timeline': '',
        'Investment / Cost': '',
        'Payment terms': '',
        'Proposal validity': '',
        'Assumptions / Exclusions': '',
      },
      logoBytes: logo,
    );
    final archive = ZipDecoder().decodeBytes(bytes);
    final document =
        utf8.decode(archive.findFile('word/document.xml')!.content);

    expect(document, contains('Short proposal'));
    expect(document, contains('Configure the new network'));
    expect(document, isNot(contains('Client contact')));
    expect(document, isNot(contains('Background / Problem')));
    expect(document, isNot(contains('________')));
  });

  test('proposal includes section images and links to attached files',
      () async {
    final logo = (await rootBundle.load('assets/ahead_africa_logo.png'))
        .buffer
        .asUint8List();
    final bytes = await createProposalDocument(
      values: const {
        'Proposal title': 'Network upgrade',
        'Proposed solution / Scope of work': '',
      },
      logoBytes: logo,
      attachments: [
        ProposalAttachment(
          name: 'rack-layout.png',
          bytes: logo,
          extension: 'png',
          section: 'Proposed solution / Scope of work',
        ),
        ProposalAttachment(
          name: 'equipment-list.pdf',
          bytes: Uint8List.fromList([1, 2, 3]),
          extension: 'pdf',
          section: 'Proposed solution / Scope of work',
          outputName: 'PROP-001_attachment_2_equipment-list.pdf',
        ),
      ],
    );
    final archive = ZipDecoder().decodeBytes(bytes);
    final document =
        utf8.decode(archive.findFile('word/document.xml')!.content);
    final relationships = utf8.decode(
      archive.findFile('word/_rels/document.xml.rels')!.content,
    );
    final images =
        archive.files.where((file) => file.name.startsWith('word/media/'));

    expect(document, contains('rack-layout.png'));
    expect(document, contains('equipment-list.pdf'));
    expect(document, contains('<w:hyperlink'));
    expect(relationships, contains('PROP-001_attachment_2_equipment-list.pdf'));
    expect(images, hasLength(2));
  });

  test('proposal renames included sections and omits hidden sections',
      () async {
    final logo = (await rootBundle.load('assets/ahead_africa_logo.png'))
        .buffer
        .asUint8List();
    final bytes = await createProposalDocument(
      values: const {
        'Background / Problem': 'Unwanted problem details',
        'Proposed solution / Scope of work': 'Configure the new network',
      },
      logoBytes: logo,
      sectionLabels: const {
        'Proposed solution / Scope of work': 'Recommended approach',
      },
      hiddenSections: const {'Background / Problem'},
    );
    final archive = ZipDecoder().decodeBytes(bytes);
    final document =
        utf8.decode(archive.findFile('word/document.xml')!.content);

    expect(document, contains('Recommended approach'));
    expect(document, contains('Configure the new network'));
    expect(document, isNot(contains('Background / Problem')));
    expect(document, isNot(contains('Unwanted problem details')));
    expect(document, isNot(contains('Proposed solution / Scope of work')));
  });

  test('BOQ exports an Excel workbook with formulas and embedded branding',
      () async {
    final logo = (await rootBundle.load('assets/ahead_africa_logo.png'))
        .buffer
        .asUint8List();
    final bytes = createBoqWorkbook(
      projectTitle: 'Network upgrade',
      client: 'Example Client',
      reference: 'BOQ-001',
      date: '2026-11-14',
      currency: 'TZS',
      items: const [
        BoqLineItem(
          description: 'Network switch',
          unit: 'each',
          quantity: 2,
          unitRate: 150000,
        ),
      ],
      logoBytes: logo,
    );
    final archive = ZipDecoder().decodeBytes(bytes);
    final sheet = utf8.decode(
      archive.findFile('xl/worksheets/sheet1.xml')!.content,
    );
    final drawing =
        utf8.decode(archive.findFile('xl/drawings/drawing1.xml')!.content);
    final sheetRelationships = utf8.decode(
      archive.findFile('xl/worksheets/_rels/sheet1.xml.rels')!.content,
    );

    expect(sheet, contains('Network switch'));
    expect(sheet, contains('D6*E6'));
    expect(sheet, contains('SUM(F6:F6)'));
    expect(sheet, contains('https://aheadafrica.co.tz'));
    expect(sheet, contains('Garden Avenue Tower'));
    expect(sheet, contains('<oddFooter>'));
    expect(sheetRelationships, contains('https://aheadafrica.co.tz'));
    expect(drawing, contains('AHEAD AFRICA logo'));
    expect(
      archive.findFile('xl/media/ahead_africa_logo.png')!.content,
      orderedEquals(logo),
    );
    expect(sheet, isNot(contains('Generated by ZIONGZOU')));
  });

  test('BOQ includes custom columns and autofits column widths', () async {
    final logo = (await rootBundle.load('assets/ahead_africa_logo.png'))
        .buffer
        .asUint8List();
    final bytes = createBoqWorkbook(
      projectTitle: 'Network upgrade',
      client: 'Example Client',
      reference: 'BOQ-002',
      date: '2026-11-14',
      currency: 'TZS',
      customColumns: ['Equipment type', 'Unused column', ''],
      items: const [
        BoqLineItem(
          description: 'Network switch',
          unit: 'each',
          quantity: 2,
          unitRate: 150000,
          customValues: ['Switch', '', 'Rack'],
        ),
        BoqLineItem(
          description: ' ',
          unit: '',
          quantity: 0,
          unitRate: 0,
          customValues: ['', '', ''],
        ),
      ],
      logoBytes: logo,
    );
    final archive = ZipDecoder().decodeBytes(bytes);
    final sheet = utf8.decode(
      archive.findFile('xl/worksheets/sheet1.xml')!.content,
    );

    expect(sheet, contains('Equipment type'));
    expect(sheet, contains('Unused column'));
    expect(sheet, contains('Switch'));
    expect(sheet, contains('Column 3'));
    expect(sheet, contains('<c r="I6"'));
    expect(sheet, contains('Rack'));
    expect(sheet, contains('<dimension ref="A1:I'));
    expect(sheet, contains('<col min="7" max="7" width="16.00" bestFit="1"'));
    expect(sheet, contains('bestFit="1"'));
    expect(sheet, isNot(contains('<c r="B7"')));
  });
}
